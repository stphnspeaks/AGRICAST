// AgriTask: pick a quarter, look up the precomputed forecast, show it with a mini chart.
import { Q } from './db.js';
import { settings, store, fmtYield, fmtNum, toUnit, unitLabel, unitDec, qLabel, pct, enhance, reduced, riceIcon, countUp, toast } from './ui.js';
import { trendData, trendChart, qKey } from './charts.js';

const RECENT_KEY = 'agricast.recent';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export function render(el, ctx) {
  const crop = settings.get().crop;
  const info = Q.buildInfo();
  const forecasts = Q.forecasts(crop);
  const quarterly = Q.quarterly(crop);
  const years = [...new Set(forecasts.map((f) => f.year))];
  const firstFuture = forecasts.find((f) => f.kind === 'future');

  const offered = (y, q) => forecasts.find((f) => f.year === y && f.q === q);
  const quartersOf = (y) => forecasts.filter((f) => f.year === y);

  // Which quarter is selected at the start? A link like #/task?y=2026&q=3 may ask for one.
  const wantY = Number(ctx.query.get('y')), wantQ = Number(ctx.query.get('q'));
  const asked = ctx.query.has('y') || ctx.query.has('q');
  const valid = asked && offered(wantY, wantQ);
  const start = valid ? valid : firstFuture;

  const files = Q.dataFiles();
  const badges = ['Production CSV', 'Area Harvested CSV'].map((name) => {
    const f = files.find((x) => x.name === name);
    return f && f.rows_loaded > 0
      ? `<span class="badge">${name}: Loaded (${fmtNum(f.rows_loaded)} rows)</span>`
      : `<span class="badge missing">${name}: Missing</span>`;
  }).join('');

  const metrics = Q.metrics();
  const metricRows = metrics.map((m) => `<tr class="${m.is_selected ? 'sel' : ''}"><td>${m.model}${m.is_baseline ? ' <span class="pill">baseline</span>' : ''}${m.is_selected ? ' <span class="pill pred">selected</span>' : ''}</td>
    <td class="num">${fmtYield(m.mae)}</td><td class="num">${fmtYield(m.rmse)}</td><td class="num">${fmtNum(m.mape, 1)}%</td></tr>`).join('');
  const verdict = info.beats_baseline
    ? `${info.model_name} beats the seasonal-naive baseline on time-based validation, so it is used.`
    : 'Neither Ridge nor Random Forest beat the seasonal-naive baseline (same quarter last year) on time-based validation, so the baseline is used.';

  el.innerHTML = `<div class="view">
    <div><h1 class="page-title">Forecast Pampanga Rice Yield</h1>
      <p class="page-sub">Forecasts are generated by the offline model and stored in the database.</p></div>

    <div class="grid g2">
      <div class="grid" style="align-content:start">
        <section class="card reveal" aria-labelledby="setupT">
          <h2 id="setupT">Forecast setup</h2>
          <form id="form" class="grid" style="gap:16px">
            <div class="field"><label for="fCrop">Crop</label><select id="fCrop">${Q.crops().map((c) => `<option>${c}</option>`).join('')}</select></div>
            <div class="grid g2" style="gap:16px">
              <div class="field"><label for="fYear">Forecast year</label>
                <select id="fYear">${years.map((y) => `<option value="${y}" ${y === start.year ? 'selected' : ''}>${y}</option>`).join('')}</select></div>
              <div class="field"><label for="fQuarter">Forecast quarter</label><select id="fQuarter"></select></div>
            </div>
            <div id="notOffered" class="msg" role="alert" hidden></div>
            <button class="btn" id="go" type="submit">Generate forecast</button>
            <p class="note">Historical records are loaded automatically. Only quarters stored in the database are offered: past quarters (model vs actual) and the next ${forecasts.filter((f) => f.kind === 'future').length}.</p>
          </form>
        </section>
        <section class="card reveal" aria-labelledby="histT"><h2 id="histT">Historical data</h2><div class="badges">${badges}</div>
          <p class="note" style="margin-top:12px">Source: PSA OpenStat. Latest published quarter: ${qLabel(info.latest_year, info.latest_quarter)} (preliminary).</p></section>
      </div>

      <div class="grid" style="align-content:start">
        <section class="card reveal" aria-labelledby="resT" aria-live="polite">
          <h2 id="resT">Forecast result</h2><div id="result"></div></section>
        <section class="card reveal" aria-labelledby="recT">
          <div class="row"><h2 id="recT" style="margin:0">Recent forecasts</h2><button class="btn ghost sm" id="clearRecent" type="button">Clear</button></div>
          <div id="recent" style="margin-top:14px"></div></section>
      </div>
    </div>

    <section class="card reveal" aria-labelledby="cmpT">
      <h2 id="cmpT">Model comparison</h2>
      <p class="note" style="margin-bottom:10px">Rolling-origin validation over horizons 1 to 4 quarters (time-based, no random split). Errors in ${unitLabel()}.</p>
      <div style="overflow-x:auto"><table><thead><tr><th>Model</th><th class="num">MAE</th><th class="num">RMSE</th><th class="num">MAPE</th></tr></thead><tbody>${metricRows}</tbody></table></div>
      <p class="note" style="margin-top:12px">${verdict}</p>
    </section>
  </div>`;

  const $ = (s) => el.querySelector(s);
  const resultBox = $('#result');
  const emptyState = () => {
    resultBox.innerHTML = `<div class="empty">${riceIcon(84)}<span class="big">-- ${unitLabel()}</span><span>Run a forecast to see predicted yield</span></div>`;
  };

  // ----- selects -----
  const fillQuarters = (selectedQ) => {
    const y = Number($('#fYear').value);
    $('#fQuarter').innerHTML = quartersOf(y).map((f) =>
      `<option value="${f.q}" ${f.q === selectedQ ? 'selected' : ''}>Q${f.q} (${f.kind === 'future' ? 'forecast' : 'past'})</option>`).join('');
  };
  fillQuarters(start.q);
  const notOffered = $('#notOffered');
  if (asked && !valid) {
    notOffered.hidden = false;
    notOffered.textContent = `${ctx.query.get('q') ? 'Q' + ctx.query.get('q') + ' ' : ''}${ctx.query.get('y') || ''} is not offered. Choose a quarter from the list.`;
    toast('That quarter is not in the database.', 'error');
  }
  $('#fYear').addEventListener('change', () => { notOffered.hidden = true; fillQuarters(null); });

  // ----- recent list -----
  const drawRecent = () => {
    const list = store.read(RECENT_KEY, []);
    $('#recent').innerHTML = list.length
      ? `<ul class="recent">${list.map((r) => `<li><span>${r.label} <span class="pill ${r.kind === 'future' ? 'pred' : ''}">${r.kind === 'future' ? 'forecast' : 'past'}</span></span><b>${fmtYield(r.pred)} ${unitLabel()}</b></li>`).join('')}</ul>`
      : '<p class="note">No forecasts yet in this browser.</p>';
  };
  $('#clearRecent').addEventListener('click', () => { store.write(RECENT_KEY, []); drawRecent(); toast('Recent forecasts cleared.'); });

  // ----- generate -----
  async function generate(year, q) {
    const btn = $('#go');
    btn.disabled = true;
    resultBox.innerHTML = `<div class="computing"><div class="spinner"></div><span>Looking up the stored forecast...</span></div>`;
    if (!reduced()) await sleep(850);
    const row = Q.forecastOne(crop, year, q);
    btn.disabled = false;
    if (!row) {
      resultBox.innerHTML = '';
      emptyState();
      toast(`${qLabel(year, q)} is not in the database.`, 'error');
      return;
    }
    show(row);
    const list = store.read(RECENT_KEY, []);
    list.unshift({ label: qLabel(year, q), kind: row.kind, pred: row.pred });
    store.write(RECENT_KEY, list.slice(0, 5));
    drawRecent();
  }

  function show(row) {
    const err = info[`typical_error_h${row.horizon}`];
    const past = row.kind === 'backtest';
    const fact = (k, v) => `<div class="fact"><div class="k">${k}</div><div class="v">${v}</div></div>`;
    let facts = fact('Range (low-high)', `${fmtYield(row.low)} - ${fmtYield(row.high)}`);
    if (past) {
      const diff = pct(row.pred, row.actual);
      const prelim = row.year === info.latest_year && row.q === info.latest_quarter;
      facts = fact(`Actual (PSA${prelim ? ', preliminary' : ''})`, `${fmtYield(row.actual)} ${unitLabel()}`) +
        fact('Model vs actual', `${diff >= 0 ? '+' : ''}${diff.toFixed(1)}%`) + facts;
    } else {
      facts += fact('Horizon', `${row.horizon} quarter${row.horizon > 1 ? 's' : ''} ahead`);
    }
    facts += fact('Typical error', `±${fmtYield(err)} ${unitLabel()}`) + fact('Model', info.model_name);

    resultBox.innerHTML = `<span class="pill ${past ? '' : 'pred'}">${qLabel(row.year, row.q)} · ${past ? 'past quarter (backtest)' : 'forecast'}</span>
      <p class="result-num"><span id="big">0</span><small>${unitLabel()}</small></p>
      <p class="note">${past ? 'What the model predicted one quarter ahead, next to the real value.' : 'Predicted yield for Pampanga palay.'}</p>
      <div class="facts">${facts}</div>
      <div class="chart-box sm"><canvas id="mini" role="img" aria-label="Recent yields and this prediction"></canvas></div>
      <div class="legend"><span><i></i>Actual (PSA)</span><span><i class="dash"></i>Predicted</span><span><i class="band"></i>Low-high</span></div>`;
    countUp($('#big'), toUnit(row.pred), unitDec(), 1000);

    const key = qKey(row.year, row.q);
    const d = trendData(quarterly, forecasts, key - 11, key, [row.kind]);
    const last = d.labels.length - 1;
    d.low = d.low.map((v, i) => (i === last ? v : null));
    d.high = d.high.map((v, i) => (i === last ? v : null));
    trendChart($('#mini'), d, last);
  }

  $('#form').addEventListener('submit', (e) => {
    e.preventDefault();
    notOffered.hidden = true;
    generate(Number($('#fYear').value), Number($('#fQuarter').value));
  });

  emptyState();
  drawRecent();
  enhance(el);
  if (valid) generate(start.year, start.q);   // a link to a specific quarter runs it right away
}
